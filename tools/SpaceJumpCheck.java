import arc.*;
import arc.files.*;
import arc.mock.*;
import arc.util.*;
import mindustry.*;
import mindustry.net.*;
import mindustry.gen.*;
import mindustry.game.*;
import mindustry.ai.*;
import mindustry.ai.types.*;
import cryon.Type.SpaceJumpAbility;
public class SpaceJumpCheck{
 static void check(boolean ok, String message){if(!ok) throw new AssertionError(message);}
 public static void main(String[] args){
  Core.app=new MockApplication(); Core.files=new MockFiles(); Core.graphics=new MockGraphics(); Core.audio=new MockAudio();
  Core.settings=new Settings(); Core.settings.setDataDirectory(new Fi("/tmp/space-jump-check")); Core.bundle=I18NBundle.createEmptyBundle();
  Vars.headless=true; Vars.loadLocales=false; Vars.net=new Net(null); Vars.platform=new mindustry.core.Platform(){};
  Vars.init(); Vars.content.createBaseContent(); Vars.content.init();
  Vars.world.loadGenerator(300,100, tiles -> {for(int x=0;x<300;x++)for(int y=0;y<100;y++)tiles.set(x,y,new mindustry.world.Tile(x,y,mindustry.content.Blocks.sand,mindustry.content.Blocks.air,mindustry.content.Blocks.air));});
  Time.delta=1f;
  Unit u=mindustry.content.UnitTypes.flare.create(Team.sharded); u.set(100,100); u.elevation=1; u.add(); u.dead=false;
  CommandAI ai=new CommandAI(); u.controller(ai); ai.command(UnitCommand.moveCommand);
  SpaceJumpAbility a=new SpaceJumpAbility();
  check(!a.jump(u,600,100),"non-campaign manual jump allowed");
  ai.commandPosition(new arc.math.geom.Vec2(1500,100)); a.update(u); check(a.active(),"non-campaign automatic jump disabled");
  int nonCampaignTicks=0; while(a.active() && nonCampaignTicks++<1000)a.update(u);
  check(Math.abs(u.x-1060)<0.1,"non-campaign automatic jump failed");
  a.afterUpdate(u); a=new SpaceJumpAbility(); u.set(100,100); ai.clearCommands();
  Vars.state.rules.sector=mindustry.content.Planets.serpulo.sectors.first();
  ai.commandPosition(new arc.math.geom.Vec2(200,100)); a.update(u); check(u.x==100,"near move jumped");
  ai.commandPosition(new arc.math.geom.Vec2(1500,100)); ai.setStance(UnitStance.patrol,true); a.update(u); check(u.x==100,"patrol jumped");
  ai.setStance(UnitStance.patrol,false); ai.command(UnitCommand.moveCommand); ai.commandPosition(new arc.math.geom.Vec2(1500,100));
  u.rotation=180f; a.update(u); check(a.active() && u.x==100,"did not start alignment");
  check(a.chargeProgress()==0f,"charged before facing destination");
  float before=u.rotation; a.update(u); check(Math.abs(arc.math.Angles.angleDist(before,u.rotation)-u.type.rotateSpeed*u.speedMultiplier())<0.01f,"incorrect actual turn rate");
  check(a.chargeProgress()==0f,"charged while turning");
  u.rotation=77; u.set(900,200); a.afterUpdate(u); check(u.x==100 && u.rotation!=77,"controller overrode charge pose");
  int ticks=0; while(a.active() && ticks++<1000) a.update(u);
  check(!a.active() && Math.abs(u.x-1060)<0.1,"charge did not finish with capped jump: "+u.x);
  check(!a.jump(u,1700,100),"cooldown ignored");
  a.afterUpdate(u); ai.clearCommands();
  for(int i=0;i<301;i++)a.update(u);
  check(!a.jump(u,Float.NaN,100),"NaN accepted");
  check(a.jump(u,1700,100),"manual charge failed");
  check(!a.jump(u,1900,100),"duplicate charge accepted");
  Vars.state.rules.sector=null; check(!new SpaceJumpAbility().jump(u,1900,100),"non-campaign manual request bypassed guard");
  a.cancel(u);
  Vars.state.rules.sector=mindustry.content.Planets.serpulo.sectors.first();
  u.maxHealth=499; check(SpaceJumpAbility.level(u)==1,"class 1 incorrect");
  u.maxHealth=500; check(SpaceJumpAbility.level(u)==2,"class 2 incorrect");
  u.maxHealth=2000; check(SpaceJumpAbility.level(u)==3,"class 3 incorrect");
  u.maxHealth=8000; check(SpaceJumpAbility.level(u)==4,"class 4 incorrect");
  u.maxHealth=16000; u.health=1; check(SpaceJumpAbility.level(u)==5,"damage changed hull class");
  u.maxHealth=100;
  ai.command(UnitCommand.moveCommand); ai.commandPosition(new arc.math.geom.Vec2(2200,100));
  SpaceJumpAbility patrolCancel=new SpaceJumpAbility(); patrolCancel.update(u); check(patrolCancel.active(),"auto charge did not start");
  ai.setStance(UnitStance.patrol,true); patrolCancel.update(u); check(!patrolCancel.active(),"patrol did not cancel pending auto jump");
  SpaceJumpAbility copy=(SpaceJumpAbility)a.copy(); check(!copy.active() && copy.jump(u,2000,100),"copied unit shares state");
  copy.finish(u,2000,100,0); copy.afterUpdate(u); check(u.x==2000 && u.rotation==0,"remote finish pose incorrect");
  SpaceJumpAbility preview=new SpaceJumpAbility();
  u.set(100,100); arc.math.geom.Vec2 landing=new arc.math.geom.Vec2();
  preview.landing(u,2000,100,landing); check(Math.abs(landing.x-1060)<0.01 && landing.y==100,"preview range cap incorrect");
  check(!preview.active(),"preview started a charge");
  preview.landing(u,-500,-500,landing); check(landing.x>=u.hitSize/2 && landing.y>=u.hitSize/2,"preview outside map");
  preview.landing(u,800,100,landing); check(preview.jump(u,800,100),"preview confirmation rejected");
  int previewTicks=0; while(preview.active() && previewTicks++<1000)preview.update(u);
  check(u.dst(landing)<0.01,"actual destination differs from preview");
  for(String name:new String[]{"vain","roche","threshold","hyperion","oblivion"}){
   check(cryon.Features.SpaceJump.excluded(new mindustry.type.UnitType("cryon-"+name)),"excluded unit accepted: "+name);
  }
  u.apply(mindustry.content.StatusEffects.boss,60f);
  check(!cryon.Features.SpaceJump.allowed(u),"boss status accepted");
  check(!new SpaceJumpAbility().jump(u,1500,100),"boss could request manual fold");
  SpaceJumpAbility bossAuto=new SpaceJumpAbility(); ai.setStance(UnitStance.patrol,false); ai.commandPosition(new arc.math.geom.Vec2(2200,100));
  bossAuto.update(u);check(!bossAuto.active(),"boss started automatic fold");
  u.unapply(mindustry.content.StatusEffects.boss);
  Unit carrier=mindustry.content.UnitTypes.mega.create(Team.sharded);carrier.set(100,100);carrier.elevation=1;carrier.dead=false;
  CommandAI transfer=new CommandAI();carrier.controller(transfer);
  transfer.command=UnitCommand.loopPayloadCommand;
  transfer.commandPosition(new arc.math.geom.Vec2(800,100));
  transfer.commandQueue.add(new arc.math.geom.Vec2(100,100));
  SpaceJumpAbility loop=new SpaceJumpAbility();loop.update(carrier);check(loop.active(),"loop transfer could not fold");
  int transferTicks=0;while(loop.active() && transferTicks++<1000)loop.update(carrier);
  check(Math.abs(carrier.x-800)<0.01,"loop transfer did not reach its destination");
  check(transfer.command==UnitCommand.loopPayloadCommand && transfer.commandQueue.size==1,"fold changed transport command or queue");
  loop.afterUpdate(carrier);transfer.clearCommands();for(int i=0;i<301;i++)loop.update(carrier);
  transfer.commandPosition(new arc.math.geom.Vec2(100,100));loop.update(carrier);check(loop.active(),"return transfer could not fold");
  transfer.setStance(UnitStance.patrol,true);loop.update(carrier);check(!loop.active(),"loop transfer bypassed patrol exclusion");
  System.out.println("PASS: campaign-only manual input, automatic fold outside campaign, near move, patrol exclusion/cancellation, actual turn rate, alignment before charge, pose lock, delayed fold, range cap, cooldown, duplicate requests, hull classes, state isolation remote finish, boss exclusions, preview/execution parity, loop transfer outbound/return and queue preservation");
 }
}
